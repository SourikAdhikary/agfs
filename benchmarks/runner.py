def run_all_benchmarks(output_md: Path | None = None) -> dict[str, Any]:
    t0 = time.perf_counter()
    b1 = run_b1_benchmark()
    b2 = run_b2_benchmark()
    b3 = run_b3_benchmark()
    b4 = run_b4_benchmark()
    b5 = run_b5_benchmark()

    e1 = run_e1_oscillation_trap()
    e2 = run_e2_deceptive_local_optimum()
    e3 = run_e3_test_tampering_trap()
    e4 = run_e4_cross_branch_lesson()
    total_sec = round(time.perf_counter() - t0, 2)

    results: dict[str, Any] = {
        "environment": {
            "os": f"{platform.system()} {platform.release()} ({platform.machine()})",
            "python": platform.python_version(),
            "sqlite": sqlite3.sqlite_version,
            "zstd_backend": ZSTD_BACKEND,
            "apfs_clonefile_supported": supports_apfs_clonefile(),
            "total_suite_runtime_sec": total_sec,
        },
        "systems_benchmarks": {
            "B1": b1,
            "B2": b2,
            "B3": b3,
            "B4": b4,
            "B5": b5,
        },
        "agent_trap_evals": {
            "E1": e1,
            "E2": e2,
            "E3": e3,
            "E4": e4,
        },
    }

    if output_md is not None:
        md = format_benchmarks_markdown(results)
        output_md.write_text(md, encoding="utf-8")
        internal_json = output_md.parent / "internal" / "latest_benchmark_results.json"
        if internal_json.parent.exists():
            internal_json.write_text(json.dumps(results, indent=2) + "\n", encoding="utf-8")

    return results


